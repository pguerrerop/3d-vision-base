def list_pipelines() -> list[dict[str, Any]]:
    pipelines: list[dict[str, Any]] = []
    for pipeline in PIPELINES:
        payload = dict(
            pipeline,
            stages=[dict(stage) for stage in pipeline["stages"]],
            composition=dict(pipeline.get("composition") or {}),
        )
        payload["processing_units"] = _processing_units_for_pipeline(payload)
        if payload["processing_units"]:
            payload["processing_unit_registry_version"] = PROCESSING_UNIT_REGISTRY_VERSION
        pipelines.append(payload)
    return pipelines


def get_pipeline(pipeline_id: str) -> dict[str, Any] | None:
    for pipeline in list_pipelines():
        if pipeline["id"] == pipeline_id or pipeline["name"] == pipeline_id:
            return pipeline
    return None


def default_pipeline_info(pipeline_id: str = "3d_ball_inspection") -> dict[str, Any]:
    pipeline = get_pipeline(pipeline_id)
    if pipeline is None:
        raise KeyError(f"Unknown pipeline: {pipeline_id}")
    return pipeline


def list_processing_units(pipeline_id: str = "3d_ball_inspection") -> list[dict[str, Any]]:
    pipeline = default_pipeline_info(pipeline_id)
    return [dict(stage) for stage in pipeline["stages"]]


def get_processing_unit(stage_id: str, pipeline_id: str = "3d_ball_inspection") -> dict[str, Any] | None:
    for stage in list_processing_units(pipeline_id):
        if stage.get("id") == stage_id or stage.get("stage_id") == stage_id:
            return stage
    return None


def list_processing_unit_definitions(pipeline_id: str) -> list[dict[str, Any]]:
    pipeline = get_pipeline(pipeline_id)
    if pipeline is None:
        return []
    return [dict(item) for item in pipeline.get("processing_units") or []]


def get_processing_unit_definition(pipeline_id: str, unit_id: str) -> dict[str, Any] | None:
    for unit in list_processing_unit_definitions(pipeline_id):
        if unit.get("id") == unit_id:
            return unit
    return None


def _processing_units_for_pipeline(pipeline: dict[str, Any]) -> list[dict[str, Any]]:
    pipeline_id = str(pipeline.get("id") or "")
    stage_schemas: dict[str, dict[str, Any]] = {}
    for stage in pipeline.get("stages") or []:
        if not isinstance(stage, dict):
            continue
        stage_id = str(stage.get("id") or "")
        schema = stage.get("parameter_schema")
        if stage_id and isinstance(schema, dict):
            stage_schemas[stage_id] = schema
    return processing_units_for_pipeline(
        pipeline_id,
        stage_parameter_schemas=stage_schemas,
    )


