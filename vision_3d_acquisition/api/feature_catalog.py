from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from vision_3d_acquisition.ml.features.schemas import FEATURE_COLUMNS


@dataclass(frozen=True)
class FeatureDefinition:
    feature_key: str
    display_name: str
    family: str
    family_label: str
    source_stage: str
    unit: str | None
    formula: str
    algorithm_summary: str
    inputs: tuple[str, ...]
    interpretation: str
    caveats: tuple[str, ...] = ()
    stable_schema: bool = False
    diagnostic_only: bool = False
    experimental: bool = False
    higher_is_worse: bool | None = None
    expected_range: tuple[float, float] | None = None
    display_precision: int | None = None
    preferred_chart_scale: str = "linear"
    studio_stage: str | None = None
    source_metric_path: str = ""
    legacy_aliases: tuple[str, ...] = ()
    extraction_paths: tuple[str, ...] = field(default_factory=tuple)

    def payload(self) -> dict[str, Any]:
        return {
            "key": self.feature_key,
            "feature_key": self.feature_key,
            "display_name": self.display_name,
            "semantic_group": self.family_label,
            "family": self.family,
            "family_label": self.family_label,
            "unit": self.unit,
            "description": self.algorithm_summary,
            "source_stage": self.source_stage,
            "source_metric_path": self.source_metric_path,
            "formula": self.formula,
            "algorithm_summary": self.algorithm_summary,
            "inputs": list(self.inputs),
            "interpretation": self.interpretation,
            "caveats": list(self.caveats),
            "stable_schema": self.stable_schema,
            "diagnostic_only": self.diagnostic_only,
            "experimental": self.experimental,
            "higher_is_worse": self.higher_is_worse,
            "expected_range": list(self.expected_range) if self.expected_range is not None else None,
            "display_precision": self.display_precision,
            "preferred_chart_scale": self.preferred_chart_scale,
            "studio_stage": self.studio_stage or self.source_stage,
            "legacy_aliases": list(self.legacy_aliases),
        }


