def guess_feature_source_stage(feature_key: str) -> str:
    if feature_key.startswith("plane_residual_"):
        return "detect_belt_plane"
    if feature_key in {"confidence"}:
        return "classification"
    if feature_key in {"valid_pixel_ratio", "invalid_pixel_ratio", "bbox_crop_ratio", "roi_occupancy_ratio", "border_touch_ratio", "segmentation_foreground_ratio"}:
        return "segmentation"
    if feature_key.startswith("runtime_"):
        return "classification"
    return "measurement"


def guess_feature_family(feature_key: str) -> tuple[str, str]:
    if feature_key in {"confidence"}:
        return "classification_diagnostics", "Classification diagnostics"
    if feature_key.startswith("plane_residual_"):
        return "plane_quality", "Plane fit quality"
    if feature_key in {"valid_pixel_ratio", "invalid_pixel_ratio", "height_min", "height_max", "height_mean", "height_std", "height_p95", "height_p99"}:
        return "data_quality", "Data quality / coverage"
    if feature_key in {"border_touch_ratio", "segmentation_foreground_ratio", "bbox_crop_ratio", "roi_occupancy_ratio"}:
        return "segmentation_quality", "Segmentation quality"
    if feature_key.endswith("_mm3") or "volume" in feature_key:
        return "volume_proxy", "Volume / mass proxy"
    if "sphere" in feature_key or "deformation" in feature_key or "curvature" in feature_key:
        return "sphere_consistency", "Sphere consistency"
    if "height" in feature_key:
        return "height_metrics", "Height metrics"
    if "damage" in feature_key or "roughness" in feature_key:
        return "damage_metrics", "Damage / deformation"
    if "eccentricity" in feature_key or "radial" in feature_key or "roundness" in feature_key or "compactness" in feature_key or "solidity" in feature_key:
        return "footprint_geometry", "Footprint geometry"
    return "data_quality", "Diagnostic / engineering features"


def guess_feature_unit(feature_key: str) -> str | None:
    if feature_key.endswith("_mm3") or "volume" in feature_key:
        return "mm3"
    if feature_key.endswith("_mm2"):
        return "mm2"
    if feature_key.endswith("_mm") or "residual" in feature_key:
        return "mm"
    if feature_key.endswith("_ratio") or "eccentricity" in feature_key or "roundness" in feature_key or "compactness" in feature_key or "solidity" in feature_key or "confidence" == feature_key:
        return "ratio"
    if "score" in feature_key or "confidence" in feature_key or "flatness" in feature_key:
        return "score"
    return None


def fallback_feature_definition(feature_key: str) -> FeatureDefinition:
    family, family_label = guess_feature_family(feature_key)
    source_stage = guess_feature_source_stage(feature_key)
    unit = guess_feature_unit(feature_key)
    return FeatureDefinition(
        feature_key=feature_key,
        display_name=feature_key.replace("_", " ").strip().title(),
        family=family,
        family_label=family_label,
        source_stage=source_stage,
        unit=unit,
        formula="TODO",
        algorithm_summary="Feature discovered from result payload without a curated catalog entry yet.",
        inputs=("object result payload",),
        interpretation="Use with caution until the canonical feature catalog entry is completed.",
        caveats=("Catalog metadata is still incomplete for this feature.",),
        stable_schema=False,
        diagnostic_only=True,
        experimental=True,
        higher_is_worse=None,
        preferred_chart_scale="linear",
        studio_stage=source_stage,
        source_metric_path=f"objects[].{feature_key}",
        extraction_paths=(feature_key,),
    )


def feature_definition_for_key(feature_key: str) -> FeatureDefinition:
    return FEATURE_REGISTRY.get(feature_key) or fallback_feature_definition(feature_key)


def all_registered_feature_definitions() -> list[dict[str, Any]]:
    return [feature_definition_for_key(key).payload() for key in sorted(FEATURE_REGISTRY)]


def discover_numeric_object_feature_keys(raw_object: dict[str, Any]) -> set[str]:
    discovered: set[str] = set()
    for key, definition in FEATURE_REGISTRY.items():
        for path in definition.extraction_paths:
            if path and numeric_path_exists(raw_object, path):
                discovered.add(key)
                break
    return discovered


def numeric_path_exists(raw_object: dict[str, Any], path: str) -> bool:
    current: Any = raw_object
    for part in path.split("."):
        if not isinstance(current, dict):
            return False
        current = current.get(part)
    return isinstance(current, (int, float)) and not isinstance(current, bool)


def stable_schema_feature_keys() -> set[str]:
    return set(FEATURE_COLUMNS)


